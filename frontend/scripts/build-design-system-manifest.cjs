#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");
const prettier = require("prettier");

const frontendRoot = path.resolve(__dirname, "..");
const manifestPath = path.join(
  frontendRoot,
  "src/features/design-system/certifiedStoryManifest.ts",
);
const certifiedPath = path.join(frontendRoot, "design-system-certified.json");
const tokensPath = path.join(frontendRoot, "tokens.json");
const certified = JSON.parse(fs.readFileSync(certifiedPath, "utf8"));
const tokens = JSON.parse(fs.readFileSync(tokensPath, "utf8"));

const tokenNames = new Set(tokens.tokens.map(({ token }) => token));
const sourceTokenPattern = /\b(?:token|status|chart)-[a-zA-Z0-9-]+\b/g;
const propNamePattern = /^\s*(?:readonly\s+)?([a-zA-Z_$][\w$]*)(\?)?\s*(?::|\()/;
const variantPropPattern = /^\s*(?:readonly\s+)?(variant|size|tone|status|kind|orientation)(?:\?)?\s*:\s*([^;]+)[;,]?\s*$/;
const stringUnionPattern = /["']([^"']+)["']/g;

function collectPropNames(source) {
  const propsDeclaration = /(?:interface|type)\s+\w*Props(?:\s*<[^>]+>)?[^{}]*\{/m.exec(source);
  if (!propsDeclaration) return [];

  const openBrace = propsDeclaration.index + propsDeclaration[0].lastIndexOf("{");
  let depth = 0;
  let bodyEnd = openBrace;
  for (; bodyEnd < source.length; bodyEnd += 1) {
    if (source[bodyEnd] === "{") depth += 1;
    if (source[bodyEnd] === "}") {
      depth -= 1;
      if (depth === 0) break;
    }
  }

  const body = source.slice(openBrace + 1, bodyEnd);
  let nestedDepth = 0;
  const props = [];
  for (const line of body.split(/\r?\n/)) {
    if (nestedDepth === 0) {
      const property = propNamePattern.exec(line);
      if (property) props.push(`${property[1]}${property[2] ? "?" : ""}`);
    }
    for (const char of line) {
      if (char === "{") nestedDepth += 1;
      if (char === "}") nestedDepth -= 1;
    }
  }
  return [...new Set(props)];
}

function collectVariants(source) {
  const aliases = new Map();
  for (const match of source.matchAll(/(?:export\s+)?type\s+(\w+)\s*=\s*([^;]+);/g)) {
    aliases.set(match[1], match[2]);
  }

  const variants = new Set();
  for (const line of source.split(/\r?\n/)) {
    const field = variantPropPattern.exec(line);
    if (!field) continue;
    const typeText = aliases.get(field[2].trim()) ?? field[2];
    for (const option of typeText.matchAll(stringUnionPattern)) {
      variants.add(`${field[1]}:${option[1]}`);
    }
  }
  return [...variants].sort();
}

function titleFor(file) {
  return path
    .basename(file)
    .replace(/\.view\.tsx$/, "")
    .replace(/\.tsx?$/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2");
}

function categoryFor(file) {
  if (file === "src/features/theoretical-shifts/components/listTokens.ts") return "token-gallery";
  if (file.startsWith("src/components/ui/")) return "primitive";
  if (file.startsWith("src/components/layout/")) return "layout-shell";
  if (file.startsWith("src/components/")) return "foundation";
  if (file.startsWith("src/features/") && file.includes("/views/")) return "feature-view";
  return "domain-component";
}

function storyIdFor(file) {
  const slug = file
    .replace(/^src\//, "")
    .replace(/\.view\.tsx$/, "")
    .replace(/\.tsx?$/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
  return `certified-${slug}`;
}

const entries = certified.files.map((file) => {
  const sourcePath = path.join(frontendRoot, file);
  if (!fs.existsSync(sourcePath)) throw new Error(`Archivo certificado ausente: ${file}`);
  const source = fs.readFileSync(sourcePath, "utf8");
  const sourceTokens = [...new Set(source.match(sourceTokenPattern) ?? [])]
    .filter((token) => tokenNames.has(token))
    .sort();

  return {
    path: file,
    title: titleFor(file),
    storyId: storyIdFor(file),
    category: categoryFor(file),
    tokens: sourceTokens,
    variants: collectVariants(source),
    props: collectPropNames(source),
  };
});

const duplicateIds = entries
  .map(({ storyId }) => storyId)
  .filter((storyId, index, all) => all.indexOf(storyId) !== index);
if (duplicateIds.length > 0) throw new Error(`Story IDs duplicados: ${duplicateIds.join(", ")}`);

const outputSource = `/* Generated by scripts/build-design-system-manifest.cjs. Do not edit. */
export type CertifiedDesignSystemCategory =
  | "primitive"
  | "domain-component"
  | "feature-view"
  | "layout-shell"
  | "foundation"
  | "token-gallery";

export interface CertifiedDesignSystemStory {
  path: string;
  title: string;
  storyId: string;
  category: CertifiedDesignSystemCategory;
  tokens: readonly string[];
  variants: readonly string[];
  props: readonly string[];
}

export const CERTIFIED_DESIGN_SYSTEM_STORIES = ${JSON.stringify(entries, null, 2)} as const satisfies readonly CertifiedDesignSystemStory[];

export function getCertifiedDesignSystemStory(path: string): CertifiedDesignSystemStory | undefined {
  return CERTIFIED_DESIGN_SYSTEM_STORIES.find((entry) => entry.path === path);
}
`;

async function syncManifest() {
  const prettierConfig = (await prettier.resolveConfig(manifestPath)) ?? {};
  const output = await prettier.format(outputSource, {
    ...prettierConfig,
    filepath: manifestPath,
    parser: "typescript",
  });
  const checkOnly = process.argv.includes("--check");
  if (checkOnly) {
    const current = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, "utf8") : "";
    if (current !== output) {
      console.error("El manifiesto certificado está desactualizado. Ejecuta npm run catalog:manifest.");
      process.exitCode = 1;
    } else {
      console.log(`Manifiesto Storybook sincronizado: ${entries.length} entradas.`);
    }
  } else {
    fs.writeFileSync(manifestPath, output);
    console.log(`Manifiesto Storybook generado: ${entries.length} entradas.`);
  }
}

syncManifest().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
